package usecase

import (
	"encoding/json"
	"fmt"
	"strings"

	"github.com/Frank5ive/goforge/internal/domain"
)

// OpenAPIFile is where a generated project keeps its OpenAPI document, which
// the openapi package embeds and serves at /openapi.json.
const OpenAPIFile = "openapi/openapi.json"

// openAPIVersion is the version of the OpenAPI Specification the document follows.
const openAPIVersion = "3.1.0"

// object is a JSON object whose keys are written in sorted order.
type object = map[string]any

// openAPIDoc is the document, with its top-level keys in the order people
// expect to read them.
type openAPIDoc struct {
	OpenAPI    string              `json:"openapi"`
	Info       object              `json:"info"`
	Servers    []object            `json:"servers,omitempty"`
	Paths      map[string]pathItem `json:"paths"`
	Components map[string]object   `json:"components"`
}

type pathItem map[string]operation // by lowercase method

type operation struct {
	Summary     string            `json:"summary"`
	OperationID string            `json:"operationId"`
	Tags        []string          `json:"tags"`
	Parameters  []object          `json:"parameters,omitempty"`
	RequestBody object            `json:"requestBody,omitempty"`
	Responses   map[string]object `json:"responses"`
}

// buildOpenAPI returns the OpenAPI 3.1 document for the project the manifest
// describes: its health endpoints, and for each resource its paths, schemas,
// pagination, validation rules, and error responses.
func buildOpenAPI(m domain.Manifest) ([]byte, error) {
	title := m.AppName
	if title == "" {
		title = m.Module
	}
	doc := openAPIDoc{
		OpenAPI: openAPIVersion,
		Info: object{
			"title":   title + " API",
			"version": "0.1.0",
			"description": "Generated by GoForge from " + domain.ManifestFile + " and regenerated by `goforge add resource`. " +
				"Don't edit it by hand: changes are overwritten.",
		},
		Paths: map[string]pathItem{},
		Components: map[string]object{
			"schemas": {"Error": errorSchema()},
		},
	}
	if m.Port > 0 {
		doc.Servers = []object{{"url": fmt.Sprintf("http://localhost:%d", m.Port), "description": "Local development"}}
	}
	addOperationalPaths(&doc)

	schemas := doc.Components["schemas"]
	for _, r := range m.Resources {
		addResource(&doc, schemas, r, referencedBy(m, r))
	}

	content, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(content, '\n'), nil
}

// referencedBy reports whether another resource has a ref field to r, which
// makes deleting one of r's items a 409 while it is referenced.
func referencedBy(m domain.Manifest, r domain.ManifestResource) bool {
	for _, other := range m.Resources {
		for _, f := range other.Fields {
			if f.Type == domain.FieldRef && f.Ref == r.Name {
				return true
			}
		}
	}
	return false
}

func schemaRef(schema string) object { return object{"$ref": "#/components/schemas/" + schema} }

func errorSchema() object {
	return object{
		"type":     "object",
		"required": []string{"error"},
		"properties": object{
			"error":      object{"type": "string", "description": "What went wrong."},
			"request_id": object{"type": "string", "description": "Matches the X-Request-ID response header and the server's log lines for the request."},
			"detail":     object{"type": "string", "description": "The cause of a 500. Only set with APP_ENV=development."},
		},
	}
}

func errorResponse(description string) object {
	return object{"description": description, "content": object{"application/json": object{"schema": schemaRef("Error")}}}
}

func jsonResponse(description string, schema object) object {
	return object{"description": description, "content": object{"application/json": object{"schema": schema}}}
}

func jsonBody(schema string) object {
	return object{"required": true, "content": object{"application/json": object{"schema": schemaRef(schema)}}}
}

// addOperationalPaths adds the endpoints every project has.
func addOperationalPaths(doc *openAPIDoc) {
	doc.Paths["/health"] = pathItem{"get": operation{
		Summary: "Liveness check", OperationID: "getHealth", Tags: []string{"operations"},
		Responses: map[string]object{"200": jsonResponse("The service is running.", object{
			"type":     "object",
			"required": []string{"status", "timestamp", "service"},
			"properties": object{
				"status":    object{"type": "string", "examples": []string{"healthy"}},
				"timestamp": object{"type": "string", "format": "date-time"},
				"service":   object{"type": "string"},
			},
		})},
	}}
	ready := func(description string) object {
		return jsonResponse(description, object{
			"type":       "object",
			"required":   []string{"status"},
			"properties": object{"status": object{"type": "string"}},
		})
	}
	doc.Paths["/readyz"] = pathItem{"get": operation{
		Summary: "Readiness check", OperationID: "getReady", Tags: []string{"operations"},
		Responses: map[string]object{
			"200": ready("The service and its dependencies, such as the database, are ready."),
			"503": ready("A dependency is unavailable."),
		},
	}}
	doc.Paths["/openapi.json"] = pathItem{"get": operation{
		Summary: "This document", OperationID: "getOpenAPI", Tags: []string{"operations"},
		Responses: map[string]object{"200": {
			"description": "The OpenAPI 3.1 document describing this API.",
			"content":     object{"application/json": object{"schema": object{"type": "object"}}},
		}},
	}}
}

// addResource adds a resource's schemas and its two paths.
func addResource(doc *openAPIDoc, schemas object, r domain.ManifestResource, referenced bool) {
	name := domain.CamelCase(r.Name)
	human := strings.ReplaceAll(r.Name, "_", " ")
	humanPlural := strings.ReplaceAll(r.Plural, "_", " ")
	// The same path the generated routes use: underscores become hyphens
	path := "/" + strings.ReplaceAll(r.Plural, "_", "-")
	itemPath := path + "/{id}"
	tag := []string{r.Plural}

	fields := object{}
	var required []string
	for _, f := range r.Fields {
		fields[f.Name] = fieldSchema(f)
		if f.Required() {
			required = append(required, f.Name)
		}
	}
	input := object{"type": "object", "properties": fields, "additionalProperties": false}
	if len(required) > 0 {
		input["required"] = required
	}
	patch := object{"type": "object", "properties": fields, "additionalProperties": false,
		"description": "Only the fields sent are changed; each is checked by the same rules as in " + name + "Input."}

	stored := object{
		"id":         object{"type": "string", "readOnly": true},
		"created_at": object{"type": "string", "format": "date-time", "readOnly": true},
		"updated_at": object{"type": "string", "format": "date-time", "readOnly": true},
	}
	for k, v := range fields {
		stored[k] = v
	}
	storedRequired := append([]string{"id"}, required...)
	storedRequired = append(storedRequired, "created_at", "updated_at")

	schemas[name] = object{"type": "object", "required": storedRequired, "properties": stored}
	schemas[name+"Input"] = input
	schemas[name+"Patch"] = patch
	schemas[name+"Page"] = object{
		"type":     "object",
		"required": []string{"items", "total", "limit", "offset"},
		"properties": object{
			"items":  object{"type": "array", "items": schemaRef(name)},
			"total":  object{"type": "integer", "description": "How many " + humanPlural + " exist."},
			"limit":  object{"type": "integer", "description": "The page size used."},
			"offset": object{"type": "integer", "description": "How many " + humanPlural + " were skipped."},
		},
	}

	idParam := object{"name": "id", "in": "path", "required": true, "schema": object{"type": "string"}, "description": "The ID of the " + human + "."}
	internal := errorResponse("An unexpected error. The body has a request_id to find it in the logs.")
	invalid := errorResponse("A field broke a validation rule; the message lists every failed rule.")
	badRequest := errorResponse("Malformed JSON, an unknown field, or an invalid parameter.")
	tooLarge := errorResponse("The request body is larger than MAX_BODY_BYTES.")
	notFound := errorResponse("No " + human + " has this ID.")

	doc.Paths[path] = pathItem{
		"get": operation{
			Summary: "List " + humanPlural, OperationID: "list" + name + "s", Tags: tag,
			Parameters: []object{
				{"name": "limit", "in": "query", "description": "Page size (default 20, at most 100).", "schema": object{"type": "integer", "minimum": 0, "maximum": 100, "default": 20}},
				{"name": "offset", "in": "query", "description": "How many to skip.", "schema": object{"type": "integer", "minimum": 0, "default": 0}},
			},
			Responses: map[string]object{
				"200": jsonResponse("A page of "+humanPlural+", oldest first.", schemaRef(name+"Page")),
				"400": badRequest, "500": internal,
			},
		},
		"post": operation{
			Summary: "Create a " + human, OperationID: "create" + name, Tags: tag,
			RequestBody: jsonBody(name + "Input"),
			Responses: map[string]object{
				"201": func() object {
					r := jsonResponse("The new "+human+".", schemaRef(name))
					r["headers"] = object{"Location": object{"description": "The path of the new " + human + ".", "schema": object{"type": "string"}}}
					return r
				}(),
				"400": badRequest, "413": tooLarge, "422": invalid, "500": internal,
			},
		},
	}

	deleteResponses := map[string]object{"204": {"description": "Deleted."}, "404": notFound, "500": internal}
	if referenced {
		deleteResponses["409"] = errorResponse("Other items still refer to this " + human + ", so it can't be deleted.")
	}
	doc.Paths[itemPath] = pathItem{
		"get": operation{
			Summary: "Get a " + human, OperationID: "get" + name, Tags: tag, Parameters: []object{idParam},
			Responses: map[string]object{"200": jsonResponse("The "+human+".", schemaRef(name)), "404": notFound, "500": internal},
		},
		"put": operation{
			Summary: "Replace a " + human, OperationID: "replace" + name, Tags: tag, Parameters: []object{idParam},
			RequestBody: jsonBody(name + "Input"),
			Responses: map[string]object{
				"200": jsonResponse("The updated "+human+".", schemaRef(name)),
				"400": badRequest, "404": notFound, "413": tooLarge, "422": invalid, "500": internal,
			},
		},
		"patch": operation{
			Summary: "Change some fields of a " + human, OperationID: "patch" + name, Tags: tag, Parameters: []object{idParam},
			RequestBody: jsonBody(name + "Patch"),
			Responses: map[string]object{
				"200": jsonResponse("The updated "+human+".", schemaRef(name)),
				"400": badRequest, "404": notFound, "413": tooLarge, "422": invalid, "500": internal,
			},
		},
		"delete": operation{
			Summary: "Delete a " + human, OperationID: "delete" + name, Tags: tag, Parameters: []object{idParam},
			Responses: deleteResponses,
		},
	}
}

// fieldSchema returns the JSON Schema of a field, with its validation rules.
func fieldSchema(f domain.Field) object {
	s := object{}
	switch f.Type {
	case domain.FieldString:
		s["type"] = "string"
	case domain.FieldEmail:
		s["type"], s["format"] = "string", "email"
	case domain.FieldRef:
		s["type"] = "string"
		s["description"] = "The ID of an existing " + strings.ReplaceAll(f.Ref, "_", " ") + "."
	case domain.FieldInt:
		s["type"] = "integer"
	case domain.FieldFloat:
		s["type"] = "number"
	case domain.FieldBool:
		s["type"] = "boolean"
	case domain.FieldTime:
		s["type"], s["format"] = "string", "date-time"
	}

	minKey, maxKey := "minimum", "maximum"
	if f.IsText() {
		minKey, maxKey = "minLength", "maxLength"
	}
	if f.Min != nil {
		s[minKey] = *f.Min
	}
	if f.Max != nil {
		s[maxKey] = *f.Max
	}
	return s
}
