package domain

import (
	"errors"
	"fmt"
)

// Error codes identify a failure for programs, such as an AI agent reading
// `goforge --json` output. They are stable: new codes may be added, but an
// existing code keeps its meaning.
const (
	// CodeInvalidInput: a name, field, flag value, or option is not valid.
	CodeInvalidInput = "invalid_input"
	// CodeNotAProject: the directory is not a project created by goforge generate.
	CodeNotAProject = "not_a_goforge_project"
	// CodeAlreadyExists: the project, resource, or database already exists.
	CodeAlreadyExists = "already_exists"
	// CodeMarkerMissing: a file was edited and lost a // goforge: marker comment
	// that GoForge needs to update it.
	CodeMarkerMissing = "marker_missing"
	// CodeOutdatedProject: the project, or a resource it refers to, was
	// generated by an earlier GoForge version that lacks code the command needs.
	CodeOutdatedProject = "outdated_project"
	// CodeDependencyFailed: adding a Go module dependency failed.
	CodeDependencyFailed = "dependency_failed"
	// CodeWriteFailed: a file or directory could not be written.
	CodeWriteFailed = "write_failed"
	// CodeInternal: anything else.
	CodeInternal = "internal_error"
)

// CodedError gives err an error code, and optionally a hint on how to fix it,
// without changing its message.
type CodedError struct {
	Code string
	Hint string
	Err  error
}

func (e *CodedError) Error() string { return e.Err.Error() }

func (e *CodedError) Unwrap() error { return e.Err }

// WithCode returns err with the given error code.
func WithCode(code string, err error) error {
	return &CodedError{Code: code, Err: err}
}

// WithHint returns err with the given error code and a hint for fixing it.
func WithHint(code, hint string, err error) error {
	return &CodedError{Code: code, Hint: hint, Err: err}
}

// ErrorHint returns the hint attached to err with WithHint, or "".
func ErrorHint(err error) string {
	var coded *CodedError
	if errors.As(err, &coded) {
		return coded.Hint
	}
	return ""
}

// ErrorCode returns err's error code: the outermost code attached with WithCode,
// otherwise one inferred from the error's type, otherwise CodeInternal.
func ErrorCode(err error) string {
	var coded *CodedError
	if errors.As(err, &coded) {
		return coded.Code
	}
	var validation *ValidationError
	var generation *GenerationError
	if errors.As(err, &validation) || (errors.As(err, &generation) && generation.Step == "validation") {
		return CodeInvalidInput
	}
	var fsErr *FileSystemError
	if errors.As(err, &fsErr) {
		return CodeWriteFailed
	}
	return CodeInternal
}

// DomainError represents a base error type for domain-specific errors.
type DomainError struct {
	Code    string
	Message string
	Err     error
}

func (e *DomainError) Error() string {
	if e.Err != nil {
		return fmt.Sprintf("%s: %s: %v", e.Code, e.Message, e.Err)
	}
	return fmt.Sprintf("%s: %s", e.Code, e.Message)
}

func (e *DomainError) Unwrap() error {
	return e.Err
}

// ValidationError represents validation failures in the domain layer.
type ValidationError struct {
	Field   string
	Message string
}

func (e *ValidationError) Error() string {
	if e.Field != "" {
		return fmt.Sprintf("validation error [%s]: %s", e.Field, e.Message)
	}
	return fmt.Sprintf("validation error: %s", e.Message)
}

// NewValidationError creates a new validation error.
func NewValidationError(message string) *ValidationError {
	return &ValidationError{
		Message: message,
	}
}

// NewValidationErrorWithField creates a new validation error with a field name.
func NewValidationErrorWithField(field, message string) *ValidationError {
	return &ValidationError{
		Field:   field,
		Message: message,
	}
}

// GenerationError represents errors during server generation.
type GenerationError struct {
	Step    string
	Message string
	Err     error
}

// Error returns the message and cause. The step is for programs (see ErrorCode),
// so it is left out.
func (e *GenerationError) Error() string {
	if e.Err != nil {
		return fmt.Sprintf("%s: %v", e.Message, e.Err)
	}
	return e.Message
}

func (e *GenerationError) Unwrap() error {
	return e.Err
}

// NewGenerationError creates a new generation error.
func NewGenerationError(step, message string, err error) *GenerationError {
	return &GenerationError{
		Step:    step,
		Message: message,
		Err:     err,
	}
}

// TemplateError represents errors during template rendering.
type TemplateError struct {
	TemplateName string
	Message      string
	Err          error
}

func (e *TemplateError) Error() string {
	if e.Err != nil {
		return fmt.Sprintf("template error [%s]: %s: %v", e.TemplateName, e.Message, e.Err)
	}
	return fmt.Sprintf("template error [%s]: %s", e.TemplateName, e.Message)
}

func (e *TemplateError) Unwrap() error {
	return e.Err
}

// NewTemplateError creates a new template error.
func NewTemplateError(templateName, message string, err error) *TemplateError {
	return &TemplateError{
		TemplateName: templateName,
		Message:      message,
		Err:          err,
	}
}

// FileSystemError represents errors during filesystem operations.
type FileSystemError struct {
	Operation string
	Path      string
	Message   string
	Err       error
}

func (e *FileSystemError) Error() string {
	if e.Err != nil {
		return fmt.Sprintf("filesystem error [%s] at %s: %s: %v", e.Operation, e.Path, e.Message, e.Err)
	}
	return fmt.Sprintf("filesystem error [%s] at %s: %s", e.Operation, e.Path, e.Message)
}

func (e *FileSystemError) Unwrap() error {
	return e.Err
}

// NewFileSystemError creates a new filesystem error.
func NewFileSystemError(operation, path, message string, err error) *FileSystemError {
	return &FileSystemError{
		Operation: operation,
		Path:      path,
		Message:   message,
		Err:       err,
	}
}
